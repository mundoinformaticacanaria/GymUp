package com.mundoinformaticacanaria.gymup.data.images

import android.content.Context
import com.mundoinformaticacanaria.gymup.data.local.ExerciseDao
import java.io.File
import java.io.IOException
import java.nio.channels.FileChannel
import java.nio.file.Files
import java.nio.file.LinkOption
import java.nio.file.StandardOpenOption

/**
 * Idempotent startup reconciliation for USER image files left behind after a Room commit
 * or a process death between file publication and row insertion.
 *
 * Call only after backup journal recovery and seeding, while the application-wide
 * domain write barrier is held and before UI readers/writers are exposed.
 * Never infer that arbitrary legacy filenames are garbage: only UUID filenames
 * generated by ExerciseImageManager are eligible for removal.
 */
internal class UserImageOrphanReconciler(
    context: Context,
    private val exerciseDao: ExerciseDao,
    private val removeFile: (File) -> Boolean = File::delete,
    private val syncDirectory: (File) -> Unit = ::syncDirectoryMetadata,
) {
    private val filesDirectory = context.applicationContext.filesDir
    private val directory = File(filesDirectory, "exercise-images")

    suspend fun reconcile() {
        // Reject a substituted private parent before inspecting or deleting orphans.
        // Checking only the final exercise-images component could traverse a symlinked
        // filesDir and delete an unrelated external file with a canonical UUID name.
        if (!Files.isDirectory(filesDirectory.toPath(), LinkOption.NOFOLLOW_LINKS)) {
            throw IOException("Directorio privado de imágenes no seguro")
        }
        val root = directory.toPath()
        if (Files.isSymbolicLink(root)) throw IOException("Directorio de imágenes enlazado")
        if (!Files.exists(root, LinkOption.NOFOLLOW_LINKS)) return
        if (!Files.isDirectory(root, LinkOption.NOFOLLOW_LINKS)) {
            throw IOException("La ruta de imágenes no es un directorio")
        }

        val referenced = exerciseDao.getAllUserImageStorageKeys().toSet()
        val entries = directory.listFiles() ?: throw IOException("No se pudieron enumerar las imágenes")
        for (file in entries) {
            // Unknown/legacy names and in-flight .tmp files are never removed by inference.
            if (!UUID_FILE.matches(file.name)) continue
            val key = "user:${file.name}"
            if (key in referenced) continue
            val path = file.toPath()
            if (!Files.isRegularFile(path, LinkOption.NOFOLLOW_LINKS)) {
                throw IOException("Imagen huérfana no regular: ${file.name}")
            }
            // Defense in depth: a stale snapshot must not delete a newly referenced file.
            if (exerciseDao.countUserImageStorageKeyReferences(key) != 0) continue
            if (!removeFile(file) || Files.exists(path, LinkOption.NOFOLLOW_LINKS)) {
                throw IOException("No se pudo retirar la imagen huérfana: ${file.name}")
            }
            // A failed fsync is not success. Retrying after restart is safe and idempotent.
            syncDirectory(directory)
        }
    }

    private companion object {
        val UUID_FILE = Regex("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")

        fun syncDirectoryMetadata(directory: File) {
            FileChannel.open(directory.toPath(), StandardOpenOption.READ).use { it.force(true) }
        }
    }
}
